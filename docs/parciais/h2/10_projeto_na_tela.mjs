// H2 — o que a tela mostra de um projeto coordenado criado pela API (ids em /tmp/h2_10_ids.json).
import { createRequire } from "node:module";
import { readFileSync } from "node:fs";
const require = createRequire("/home/vitao/projetos/hellosquad/apps/web/package.json");
const { chromium, expect } = require("@playwright/test");
const BASE = "http://127.0.0.1:3100", OUT = "/home/vitao/projetos/hellosquad/docs/parciais/h2/browser";
const ids = JSON.parse(readFileSync("/tmp/h2_10_ids.json", "utf8"));
const browser = await chromium.launch();
const page = await (await browser.newContext({ locale: "pt-BR", viewport: { width: 1440, height: 900 } })).newPage();
await page.goto(`${BASE}/entrar`);
await page.getByLabel("Seu e-mail").fill("marina@miolo.example");
await page.getByLabel("Sua senha").fill("Senha!Teste123");
await page.getByRole("button", { name: "Entrar" }).click();
await expect(page).toHaveURL(/\/app\/miolo$/, { timeout: 30_000 });
const has = async (re) => (await page.getByText(re).count()) > 0;
await page.goto(`${BASE}/app/miolo/squad/nexo`);
await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/projeto-coordenado-projetos.png`, fullPage: true });
console.log("Projetos: 'Campanha de Natal'", await has(/Campanha de Natal/), "| 'etapa'", await has(/etapa \d de \d/i), "| 'Aguardando o motor'", await has(/Aguardando o motor/i), "| 'Nenhum projeto ainda'", await has(/Nenhum projeto ainda/));
await page.goto(`${BASE}/app/miolo/squad/nexo/trabalho/${ids.work}`);
await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/projeto-coordenado-trabalho.png`, fullPage: true });
const main = (await page.getByRole("main").innerText().catch(() => "")).replace(/\s+/g, " ");
console.log("Trabalho:", page.url().replace(BASE, ""), "| status http ok:", !/404|não encontrad/i.test(main.slice(0, 200)));
console.log("  Bia/Kaia/Otto no detalhe:", ["Bia", "Kaia", "Otto"].map((n) => main.includes(n)), "| 'Aguardando o motor'", /Aguardando o motor/i.test(main), "| 'etapa'", /etapa \d de \d/i.test(main), "| 'Estratégia'/'Peças'/'Textos'", ["Estratégia", "Peças", "Textos"].map((n) => main.includes(n)));
console.log("  trecho:", main.slice(0, 600));
await page.goto(`${BASE}/app/miolo/sala-do-squad`);
await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/projeto-coordenado-sala.png` });
const room = (await page.getByRole("region", { name: "Conversa" }).innerText().catch(() => "")).replace(/\s+/g, " ");
console.log("Sala: cartão da equipe ('estratégia e conceito')", room.includes("estratégia e conceito"), "| fala do Nexo 'Montei o squad'", room.includes("Montei o squad"), "| fala da Kaia 'motor de imagem'", room.includes("motor de imagem"));
await browser.close();
